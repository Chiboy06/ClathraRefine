import "server-only";
import { Document, Page, Text, View, StyleSheet, renderToBuffer } from "@react-pdf/renderer";
import { sha256Hex, canonical } from "../chain";

export type DocSection = { heading: string; paragraphs?: string[]; table?: { head: string[]; rows: string[][] } };
export type DocSpec = { title: string; subtitle?: string; meta?: [string, string][]; sections: DocSection[]; footer?: string };

// The built-in PDF font covers Latin-1 only, so symbols outside it are spelled out.
const SAFE: [RegExp, string][] = [
  [/₦/g, "NGN "],
  [/[−–—]/g, "-"],
  [/η/g, "eta"],
  [/ṁ/g, "m"],
  [/Δ/g, "d"],
  [/₂/g, "2"],
  [/³/g, "3"],
  [/•/g, "|"],
  [/→/g, "->"],
  [/≥/g, ">="],
  [/≤/g, "<="],
  [/[^\x00-\xff]/g, "?"],
];
export const pdfSafe = (s: string) => SAFE.reduce((acc, [re, to]) => acc.replace(re, to), s);

const st = StyleSheet.create({
  page: { padding: 40, fontSize: 10, fontFamily: "Helvetica", color: "#0f172a" },
  brand: { fontSize: 9, color: "#0891B2", marginBottom: 4, fontFamily: "Helvetica-Bold" },
  title: { fontSize: 18, fontFamily: "Helvetica-Bold", marginBottom: 4 },
  subtitle: { fontSize: 10, color: "#475569", marginBottom: 12 },
  demo: { fontSize: 8, color: "#b45309", marginBottom: 12 },
  metaRow: { flexDirection: "row", marginBottom: 2 },
  metaK: { width: 140, color: "#475569" },
  h: { fontSize: 12, fontFamily: "Helvetica-Bold", marginTop: 14, marginBottom: 6 },
  p: { marginBottom: 4, lineHeight: 1.4 },
  tr: { flexDirection: "row", borderBottomWidth: 0.5, borderColor: "#cbd5e1", paddingVertical: 4 },
  th: { flex: 1, fontFamily: "Helvetica-Bold", fontSize: 9 },
  td: { flex: 1, fontSize: 9 },
  foot: { position: "absolute", bottom: 24, left: 40, right: 40, fontSize: 7, color: "#64748b" },
});

/** Renders a document. The printed content hash covers the document body; the response also carries the PDF bytes' SHA-256. */
export async function renderDoc(spec: DocSpec): Promise<{ buf: Buffer; contentHash: string; pdfHash: string }> {
  const contentHash = await sha256Hex(canonical(spec));
  const s = (v: string) => pdfSafe(v);
  const doc = (
    <Document title={s(spec.title)} author="ClathraRefine" creator="ClathraRefine">
      <Page size="A4" style={st.page}>
        <Text style={st.brand}>CLATHRAREFINE</Text>
        <Text style={st.title}>{s(spec.title)}</Text>
        {spec.subtitle && <Text style={st.subtitle}>{s(spec.subtitle)}</Text>}
        <Text style={st.demo}>Demo document generated by the ClathraRefine prototype. Figures not from the real board are Demo or Simulated. Standards are targets, not certifications.</Text>
        {spec.meta?.map(([k, v]) => (
          <View key={k} style={st.metaRow}>
            <Text style={st.metaK}>{s(k)}</Text>
            <Text>{s(v)}</Text>
          </View>
        ))}
        {spec.sections.map((sec) => (
          <View key={sec.heading} wrap>
            <Text style={st.h}>{s(sec.heading)}</Text>
            {sec.paragraphs?.map((p, i) => (
              <Text key={i} style={st.p}>
                {s(p)}
              </Text>
            ))}
            {sec.table && (
              <View>
                <View style={st.tr}>
                  {sec.table.head.map((h) => (
                    <Text key={h} style={st.th}>
                      {s(h)}
                    </Text>
                  ))}
                </View>
                {sec.table.rows.map((r, i) => (
                  <View key={i} style={st.tr} wrap={false}>
                    {r.map((c, j) => (
                      <Text key={j} style={st.td}>
                        {s(c)}
                      </Text>
                    ))}
                  </View>
                ))}
              </View>
            )}
          </View>
        ))}
        <Text style={st.foot} fixed>
          {s(`${spec.footer ?? ""} Document content SHA-256: ${contentHash}. Generated ${new Date().toISOString()} (UTC).`)}
        </Text>
      </Page>
    </Document>
  );
  const buf = await renderToBuffer(doc);
  return { buf, contentHash, pdfHash: await sha256Hex(new Uint8Array(buf)) };
}

export function pdfResponse(r: { buf: Buffer; contentHash: string; pdfHash: string }, filename: string) {
  return new Response(new Uint8Array(r.buf), {
    headers: {
      "Content-Type": "application/pdf",
      "Content-Disposition": `attachment; filename="${filename}"`,
      "X-Document-SHA256": r.pdfHash,
      "X-Content-SHA256": r.contentHash,
    },
  });
}
